#!/usr/bin/env python3
"""Generate the public API field contracts from the exact FastAPI response models.

Run with backend dependencies installed; --check fails on drift. No app/database
startup, networking or credential reads are needed.
"""
import argparse
import json
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / 'backend'))
from app.public_models import PublicAnalysis, PublicJobPage, PublicSession, PublicReadiness, PublicSettings, PublicPlaylist
models = [PublicAnalysis, PublicJobPage, PublicSession, PublicReadiness, PublicSettings, PublicPlaylist]
def typename(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/',1)[1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(typename(v) for v in schema['anyOf'])
    kind=schema.get('type')
    if kind=='array': return f"Array<{typename(schema.get('items',{}))}>"
    if kind=='object':
        props=schema.get('properties',{})
        required=schema.get('required',[])
        lines=[f"{json.dumps(k)}{'' if k in required else '?'}: {typename(v)};" for k,v in props.items()]
        if schema.get('additionalProperties'):
            lines.append('[key: string]: unknown;')
        return '{ '+ ' '.join(lines) +' }' if lines else 'Record<string, unknown>'
    return {'integer':'number','number':'number','string':'string','boolean':'boolean','null':'null'}.get(kind,'unknown')
definitions={}
for model in models:
    schema=model.model_json_schema()
    definitions.update(schema.pop('$defs',{}))
    definitions[model.__name__]=schema
text='// Generated by scripts/export-api-contracts.py. Do not edit.\n'
text+='\n'.join(f'export type {name} = {typename(schema)};' for name,schema in sorted(definitions.items()))+'\n'
path=root/'src/features/downloads/public-contracts.generated.ts'
args=argparse.ArgumentParser();args.add_argument('--check',action='store_true');opts=args.parse_args()
if opts.check:
    if not path.exists() or path.read_text()!=text:
        raise SystemExit('Public API contract drift: run python scripts/export-api-contracts.py')
else:
    path.write_text(text)
